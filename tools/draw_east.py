def fit_glyph(path_data: str) -> str:
    """絶対座標の M/L/C/Z だけを、南と同じ外形へ写す。"""
    def fit(value: float, source_min: float, source_max: float,
            target_min: float, target_max: float) -> float:
        normalized = (value - source_min) / (source_max - source_min)
        centered = normalized * 2 - 1
        balanced = (abs(centered) ** OPTICAL_BALANCE) * (1 if centered >= 0 else -1)
        return target_min + (balanced + 1) / 2 * (target_max - target_min)

    tokens = re.findall(r"[MLCZ]|-?(?:\d+(?:\.\d*)?|\.\d+)(?:e[-+]?\d+)?", path_data)
    result: list[str] = []
    coordinate_index = 0
    for token in tokens:
        if token in "MLCZ":
            result.append(token)
            coordinate_index = 0
            continue
        value = float(token)
        if coordinate_index % 2 == 0:
            value = fit(value, SOURCE_LEFT, SOURCE_RIGHT, LEFT, RIGHT)
        else:
            value = fit(value, SOURCE_TOP, SOURCE_BOTTOM, TOP, BOTTOM)
        result.append(f"{value:.3f}")
        coordinate_index += 1
    return " ".join(result)


